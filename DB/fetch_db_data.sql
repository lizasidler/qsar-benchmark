SELECT 
    c_str.CANONICAL_SMILES,
    ANY_VALUE(a.STANDARD_TYPE),
    AVG(a.PCHEMBL_VALUE) AS av_act,
    MAX(a.PCHEMBL_VALUE) - MIN(a.PCHEMBL_VALUE) as act_diff,
    COUNT(*) AS count,
FROM chembl.TARGET_DICTIONARY t
JOIN chembl.ASSAYS assa ON t.TID = assa.TID
JOIN chembl.ACTIVITIES a ON assa.ASSAY_ID = a.ASSAY_ID
JOIN chembl.COMPOUND_STRUCTURES c_str ON a.MOLREGNO = c_str.MOLREGNO
WHERE t.CHEMBL_ID = 'CHEMBL217' 
AND a.PCHEMBL_VALUE IS NOT NULL
AND a.STANDARD_TYPE = 'Ki'
GROUP BY c_str.CANONICAL_SMILES
HAVING act_diff<1 OR count=1
ORDER BY av_act;